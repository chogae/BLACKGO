export const 로마변환 = (num) => {
    if (num <= 0) return "";

    // 1. 한글 읽기 변환 (자연스러운 한국어 방식)
    const get한글 = (n) => {
        const 한글숫자 = ["", "일", "이", "삼", "사", "오", "육", "칠", "팔", "구"];
        const 한글단위 = ["", "십", "백", "천"];
        let str = n.toString();
        let res = "";

        for (let i = 0; i < str.length; i++) {
            let digit = parseInt(str[i]);
            let unit = str.length - i - 1;

            if (digit !== 0) {
                // 10, 100, 1000 단위에서 '일'은 생략 (예: 일십 -> 십)
                let name = (digit === 1 && unit > 0) ? "" : 한글숫자[digit];
                res += name + 한글단위[unit];
            }
        }
        return res;
    };

    // 2. 로마 숫자 알파벳 변환
    const romanMap = [
        { value: 1000, symbol: "M" },
        { value: 900, symbol: "CM" },
        { value: 500, symbol: "D" },
        { value: 400, symbol: "CD" },
        { value: 100, symbol: "C" },
        { value: 90, symbol: "XC" },
        { value: 50, symbol: "L" },
        { value: 40, symbol: "XL" },
        { value: 10, symbol: "X" },
        { value: 9, symbol: "IX" },
        { value: 5, symbol: "V" },
        { value: 4, symbol: "IV" },
        { value: 1, symbol: "I" }
    ];

    let romanAlphabet = "";
    let tempNum = num;
    for (const { value, symbol } of romanMap) {
        while (tempNum >= value) {
            romanAlphabet += symbol;
            tempNum -= value;
        }
    }

    return `${romanAlphabet}(${get한글(num)})`;
};


