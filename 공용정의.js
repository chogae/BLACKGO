export const 특성공격력계산 = (레벨) => {
    if (레벨 <= 0) return 0;

    const 구간 = 10;
    const 완전한구간수 = Math.floor((레벨 - 1) / 구간);
    const 나머지레벨 = ((레벨 - 1) % 구간) + 1;

    let 총합 = 0;
    // 완전히 채워진 10레벨 단위 뭉치 합산
    for (let i = 0; i < 완전한구간수; i++) {
        총합 += 구간 * (3 + i);
    }
    // 남은 레벨 합산
    총합 += 나머지레벨 * (3 + 완전한구간수);

    return 총합;
};

export const 특성체력계산 = (레벨) => {
    if (레벨 <= 0) return 0;

    let 누적체력 = 0;
    for (let i = 1; i <= 레벨; i++) {
        // 1~10레벨: 12
        // 11~20레벨: 16 (12 + 4)
        // 21~30레벨: 20 (12 + 8)
        const 증가량 = 12 + (Math.floor((i - 1) / 10) * 4);
        누적체력 += 증가량;
    }
    return 누적체력;
};

