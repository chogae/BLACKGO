//유저스탯계산함수
function 유저스탯계산(유저) {
    let 초기값 = {};

    스탯테이블.forEach(내용 => {
        초기값[내용] = 0;
    });

    초기값.체력 = 300;
    초기값.공격력 = 90;
    초기값.방어력 = 30;
    초기값.속력 = 30;

    초기값.치명타확률 = 3;
    초기값.연타확률 = 3;
    초기값.반격확률 = 3;

    초기값.치명타피해 = 120;
    초기값.연타피해 = 120;
    초기값.반격피해 = 120;

    초기값.스킬피해 = 120;

    초기값.피해증가 = 0;
    초기값.피해감소 = 0;

    const 장착리스트 = 유저.장비.filter(item => item.장착 === 1);

    if (장착리스트) {
        장착리스트.forEach(장비 => {
            const 유형 = 장비.유형;
            const 이름 = 장비.이름;
            const 등급 = 장비.등급;

            const 장비데이터 = 장비데이터베이스[유형].find(d => d.이름 === 이름);

            if (!장비데이터) return;

            const 장착장비슬롯배율 = 1 + 유저.장비슬롯[유형] * 0.01;
            const 장착장비레벨 = 유저.장비레벨[유형];
            스탯테이블.forEach(내용 => {
                const 기본수치 = 장비데이터[내용];

                if (!기본수치) return;

                const 계산된스탯 = 블랙공식(1, (기본수치 * 등급), 장착장비레벨, 0, 1.03);
                초기값[내용] += Math.floor(계산된스탯 * 장착장비슬롯배율);
            });
        });
    }

    const 특성체력 = 블랙공식(0, 100, 유저.특성.체력, 0, 1.032);
    const 특성공격력 = 블랙공식(0, 30, 유저.특성.공격력, 0, 1.032);
    const 특성방어력 = 블랙공식(0, 10, 유저.특성.방어력, 0, 1.032);
    const 특성속력 = 블랙공식(0, 10, 유저.특성.속력, 0, 1.032);
    초기값.체력 += 특성체력;
    초기값.공격력 += 특성공격력;
    초기값.방어력 += 특성방어력;
    초기값.속력 += 특성속력;

    유저.어빌리티.forEach(슬롯 => {
        if (슬롯.이름 && 슬롯.등급 > 0 && 초기값[슬롯.이름] !== undefined) {
            const 고정스탯배열 = ['체력', '공격력', '방어력', '속력'];

            if (고정스탯배열.includes(슬롯.이름)) {
                초기값[슬롯.이름] = Math.floor(초기값[슬롯.이름] + (초기값[슬롯.이름] * 0.07 * 슬롯.등급));
            } else {
                초기값[슬롯.이름] = Math.floor(초기값[슬롯.이름] + (7 * 슬롯.등급));
            }
        }
    });

    초기값.체력 = Math.floor(초기값.체력 * (1 + (유저.그루브.레벨 * 0.01)));
    초기값.공격력 = Math.floor(초기값.공격력 * (1 + (유저.그루브.레벨 * 0.01)));
    초기값.방어력 = Math.floor(초기값.방어력 * (1 + (유저.그루브.레벨 * 0.01)));

    const 전투력 =
        Math.floor(
            0
            + (초기값.체력 * 1)
            + (초기값.공격력 * 3.3)
            + (초기값.방어력 * 10)
            + (초기값.속력 * 10)
            + 0);

    유저.모험.현재체력 = 초기값.체력;
    유저.모험.최대체력 = 초기값.체력;
    유저.쪽박체력 = Math.floor(초기값.체력 * 운빨소수.쪽박);
    유저.쪽박공격력 = Math.floor(초기값.공격력 * 운빨소수.쪽박);
    유저.쪽박방어력 = Math.floor(초기값.방어력 * 운빨소수.쪽박);

    유저.중박체력 = Math.floor(초기값.체력 * 운빨소수.중박);
    유저.중박공격력 = Math.floor(초기값.공격력 * 운빨소수.중박);
    유저.중박방어력 = Math.floor(초기값.방어력 * 운빨소수.중박);

    유저.대박체력 = Math.floor(초기값.체력 * 운빨소수.대박);
    유저.대박공격력 = Math.floor(초기값.공격력 * 운빨소수.대박);
    유저.대박방어력 = Math.floor(초기값.방어력 * 운빨소수.대박);

    유저.초대박체력 = Math.floor(초기값.체력 * 운빨소수.초대박);
    유저.초대박공격력 = Math.floor(초기값.공격력 * 운빨소수.초대박);
    유저.초대박방어력 = Math.floor(초기값.방어력 * 운빨소수.초대박);

    스탯테이블
        .filter(필터 => 필터 !== `체력`)
        .forEach(내용 => {
            유저.모험[내용] = Math.floor(초기값[내용]);
        });

    유저.전투력 = 전투력;
}

