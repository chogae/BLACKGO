    초기값.연타피해 = 120;
    초기값.반격피해 = 120;

    초기값.스킬피해 = 120;

    초기값.피해증가 = 0;
    초기값.피해감소 = 0;

    const 장착리스트 = 유저.장비.filter(item => item.장착 === 1);

